--  Create a PL/SQL Stored Procedure to get event registration count
CREATE OR REPLACE PROCEDURE get_event_reg_count (
    p_event_id IN NUMBER,
    p_total_count OUT NUMBER
) AS
BEGIN
    SELECT COUNT(*) 
    INTO p_total_count 
    FROM registrations 
    WHERE event_id = p_event_id;
EXCEPTION
    WHEN OTHERS THEN
        p_total_count := 0;
END;
