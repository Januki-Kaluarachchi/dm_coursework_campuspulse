CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) UNIQUE NOT NULL,
    password VARCHAR2(100),
    full_name VARCHAR2(100),
    contact_number VARCHAR2(15),
    email VARCHAR2(100),
    role VARCHAR2(20) DEFAULT 'STUDENT',
    status VARCHAR2(20) DEFAULT 'PENDING'
);


CREATE TABLE events (
    event_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(100) NOT NULL,
    description VARCHAR2(500),
    event_date DATE,
    venue VARCHAR2(100)
);


CREATE TABLE registrations (
    reg_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) REFERENCES users(username) ON DELETE CASCADE,
    event_id NUMBER REFERENCES events(event_id) ON DELETE CASCADE,
    reg_date DATE DEFAULT SYSDATE
);


